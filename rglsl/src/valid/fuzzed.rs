#[test]
fn modules_with_impossible_scalar_widths_are_rejected() -> crate::TestResult {
    for input in SCALAR_WIDTH_OVERFLOWS {
        let module = Module::arbitrary_take_rest(Unstructured::new(input))?;
        let mut validator = Validator::new(ValidationFlags::all(), Capabilities::default());
        assert!(validator.validate(&module).is_err(), "{:#?}", module.types);
    }
    Ok(())
}
