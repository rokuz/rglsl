fn header(bound: u32) -> Vec<u32> {
    vec![0x0723_0203, 0x0001_0000, 0x0008_000b, bound, 0]
}

fn instruction(opcode: u32, operands: &[u32]) -> Vec<u32> {
    let count = u32::try_from(operands.len() + 1).unwrap_or(u32::MAX);
    let mut words = vec![(count << 16) | opcode];
    words.extend_from_slice(operands);
    words
}

fn string_words(text: &str) -> Vec<u32> {
    let mut bytes = text.as_bytes().to_vec();
    bytes.push(0);
    while !bytes.len().is_multiple_of(4) {
        bytes.push(0);
    }
    bytes
        .chunks_exact(4)
        .map(|chunk| u32::from_le_bytes([chunk[0], chunk[1], chunk[2], chunk[3]]))
        .collect()
}

fn module(bound: u32, instructions: &[Vec<u32>]) -> Vec<u32> {
    let mut words = header(bound);
    for instruction in instructions {
        words.extend_from_slice(instruction);
    }
    words
}

fn body(text: &str) -> Vec<&str> {
    text.lines().skip(4).collect()
}

#[test]
fn matches_glslang_for_a_fragment_shader() {
    assert_eq!(disassemble(&FRAGMENT), FRAGMENT_TEXT);
    assert!(!disassemble_bytes(&FRAGMENT).failed);
}

#[test]
fn prints_ext_inst_names_of_every_set() {
    let mut instructions = Vec::new();
    for (id, set) in [
        (1, "GLSL.std.450"),
        (2, "NonSemantic.DebugPrintf"),
        (3, "SPV_AMD_shader_trinary_minmax"),
        (4, "NonSemantic.Shader.DebugInfo.100"),
        (5, "OpenCL.std"),
    ] {
        let mut operands = vec![id];
        operands.extend(string_words(set));
        instructions.push(instruction(11, &operands));
    }
    instructions.push(instruction(21, &[6, 32, 0]));
    for (result, set, entry) in [
        (7, 1, 13),
        (8, 1, 47),
        (9, 2, 1),
        (10, 3, 4),
        (11, 4, 35),
        (12, 5, 1),
    ] {
        instructions.push(instruction(12, &[6, result, set, entry]));
    }
    let text = disassemble(&module(13, &instructions));
    let lines = body(&text);
    assert_eq!(lines[5], "               6:             TypeInt 32 0");
    assert_eq!(
        lines[6],
        "               7:      6(int) ExtInst 1(GLSL.std.450) 13(Sin)"
    );
    assert_eq!(
        lines[7],
        "               8:      6(int) ExtInst 1(GLSL.std.450) 47(Unknown)"
    );
    assert_eq!(
        lines[8],
        "               9:      6(int) ExtInst 2(NonSemantic.DebugPrintf) 1(DebugPrintf)"
    );
    assert_eq!(
        lines[9],
        "              10:      6(int) ExtInst 3(SPV_AMD_shader_trinary_minmax) 4(FMax3AMD)"
    );
    assert_eq!(
        lines[10],
        "              11:      6(int) ExtInst 4(NonSemantic.Shader.DebugInfo.100) 35(DebugSource)"
    );
    assert_eq!(
        lines[11],
        "              12:      6(int) ExtInst 5(OpenCL.std) 1"
    );
}

#[test]
fn decorations_keep_glslang_quirks() {
    let mut linkage = vec![1, 41];
    linkage.extend(string_words("abc"));
    linkage.push(0);
    let text = disassemble(&module(
        2,
        &[
            instruction(71, &[1, 11, 0]),
            instruction(71, &linkage),
            instruction(72, &[1, 0, 11, 4]),
            instruction(19, &[1, 7]),
        ],
    ));
    let lines = body(&text);
    assert_eq!(
        lines[0],
        "                              Decorate 1 BuiltIn Position"
    );
    assert_eq!(
        lines[1],
        "                              Decorate 1 Linkage Attributes 6513249 0"
    );
    assert_eq!(
        lines[2],
        "                              MemberDecorate 1 0 BuiltIn CullDistance"
    );
    assert!(lines[3].ends_with(" ERROR, incorrect number of operands consumed.  At 21 instead of 22 instruction start was 19"));
}

#[test]
fn structured_control_flow_is_indented() {
    let text = disassemble(&module(
        10,
        &[
            instruction(247, &[5, 0]),
            instruction(250, &[1, 3, 4]),
            instruction(248, &[3]),
            instruction(249, &[5]),
            instruction(248, &[5]),
        ],
    ));
    let lines = body(&text);
    assert_eq!(
        lines[0],
        "                              SelectionMerge 5 None"
    );
    assert_eq!(
        lines[1],
        "                              BranchConditional 1 3 4"
    );
    assert_eq!(lines[2], "               3:               Label");
    assert_eq!(lines[3], "                                Branch 5");
    assert_eq!(lines[4], "               5:             Label");
}

#[test]
fn malformed_streams_fail_like_glslang() {
    assert_eq!(
        disassemble(&[]),
        "\nDisassembly failed: stream is too short\n"
    );
    assert_eq!(disassemble(&[1, 2, 3, 4, 5]), "Bad magic number");
    let failed = disassemble_bytes(&module(2, &[instruction(5, &[7, 0])]));
    assert!(failed.failed);
    assert!(String::from_utf8_lossy(&failed.text).ends_with("\nDisassembly failed: Bad <id>\n"));
    let mut truncated = header(4);
    truncated.push(0x0005_0005);
    let text = disassemble(&truncated);
    assert!(text.ends_with("\nDisassembly failed: stream instruction terminated too early\n"));
    let mut zero = header(4);
    zero.push(0x0000_0005);
    assert!(disassemble_bytes(&zero).failed);
}

#[test]
fn unknown_opcodes_print_like_glslang() {
    let text = disassemble(&module(4, &[instruction(9, &[0, 1])]));
    assert_eq!(body(&text), ["               1:             d"]);
}

#[test]
fn never_panics_on_prefixes_and_corruptions() {
    for length in 0..FRAGMENT.len() {
        let _ = disassemble_bytes(&FRAGMENT[..length]);
    }
    let mut state: u32 = 0x1234_5678;
    for position in 5..FRAGMENT.len() {
        for _ in 0..16 {
            state ^= state << 13;
            state ^= state >> 17;
            state ^= state << 5;
            let mut words = FRAGMENT.to_vec();
            words[position] = state;
            let _ = disassemble_bytes(&words);
            words[position] = state & 0x000f_ffff;
            let _ = disassemble_bytes(&words);
        }
    }
}
