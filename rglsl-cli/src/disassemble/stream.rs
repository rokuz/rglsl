use std::collections::BTreeMap;

use super::ext;
use super::tables::{self, Class, Kind};

const MAGIC_NUMBER: u32 = 0x0723_0203;
const WORD_COUNT_SHIFT: u32 = 16;
const OPCODE_MASK: u32 = 0xffff;

const OP_NAME: u32 = 5;
const OP_EXT_INST_IMPORT: u32 = 11;
const OP_EXT_INST: u32 = 12;
const OP_TYPE_BOOL: u32 = 20;
const OP_TYPE_INT: u32 = 21;
const OP_TYPE_FLOAT: u32 = 22;
const OP_TYPE_VECTOR: u32 = 23;
const OP_TYPE_IMAGE: u32 = 25;
const OP_TYPE_STRUCT: u32 = 30;
const OP_TYPE_POINTER: u32 = 32;
const OP_DECORATE: u32 = 71;
const OP_MEMBER_DECORATE: u32 = 72;
const OP_LOOP_MERGE: u32 = 246;
const OP_SELECTION_MERGE: u32 = 247;
const OP_BRANCH_CONDITIONAL: u32 = 250;
const OP_SWITCH: u32 = 251;
const OP_TYPE_UNTYPED_POINTER_KHR: u32 = 4417;

const DECORATION_BUILT_IN: u32 = 11;
const MEMORY_ACCESS_ALIGNED: u32 = 0x2;
const MEMORY_ACCESS_POINTER_IDS: u32 = 0x8 | 0x10;

const BAD_ID: &str = "Bad <id>";
const RUNS_OFF_THE_END: &str = "instruction runs off the end of the stream";

pub(super) struct Killed(&'static str);

impl Killed {
    pub(super) fn message(&self) -> &'static str {
        self.0
    }
}

type Step<T = ()> = Result<T, Killed>;

pub(super) struct Stream<'a> {
    out: Vec<u8>,
    words: &'a [u32],
    word: usize,
    bound: u32,
    descriptors: BTreeMap<u32, Vec<u8>>,
    nested: Vec<u32>,
    next_nested: u32,
}

enum ExtSet {
    Glsl450,
    Amd,
    Nv,
    OpenCl,
    DebugPrintf,
    DebugBreak,
    ShaderDebugInfo,
}

impl<'a> Stream<'a> {
    pub(super) fn new(words: &'a [u32]) -> Self {
        Self {
            out: Vec::new(),
            words,
            word: 0,
            bound: 0,
            descriptors: BTreeMap::new(),
            nested: Vec::new(),
            next_nested: 0,
        }
    }

    pub(super) fn into_output(self) -> Vec<u8> {
        self.out
    }

    pub(super) fn disassemble(&mut self) -> Step {
        if self.validate()? {
            self.process_instructions()?;
        }
        Ok(())
    }

    fn text(&mut self, text: &str) {
        self.out.extend_from_slice(text.as_bytes());
    }

    fn number(&mut self, value: impl std::fmt::Display) {
        self.text(&value.to_string());
    }

    fn peek(&self, offset: usize) -> Step<u32> {
        self.words
            .get(self.word + offset)
            .copied()
            .ok_or(Killed(RUNS_OFF_THE_END))
    }

    fn read(&mut self) -> Step<u32> {
        let value = self.peek(0)?;
        self.word += 1;
        Ok(value)
    }

    fn previous(&self, back: usize) -> u32 {
        self.word
            .checked_sub(back)
            .and_then(|position| self.words.get(position))
            .copied()
            .unwrap_or(0)
    }

    fn descriptor(&self, id: u32) -> &[u8] {
        self.descriptors.get(&id).map_or(&[], Vec::as_slice)
    }

    fn validate(&mut self) -> Step<bool> {
        if self.words.len() < 4 {
            return Err(Killed("stream is too short"));
        }
        if self.read()? != MAGIC_NUMBER {
            self.text("Bad magic number");
            return Ok(false);
        }
        let version = self.read()?;
        self.text(&format!("// Module Version {version:x}\n"));
        let generator = self.read()?;
        self.text(&format!("// Generated by (magic number): {generator:x}\n"));
        self.bound = self.read()?;
        let bound = self.bound;
        self.text(&format!("// Id's are bound by {bound}\n\n"));
        if self.read()? != 0 {
            return Err(Killed("bad schema, must be 0"));
        }
        Ok(true)
    }

    fn process_instructions(&mut self) -> Step {
        while self.word < self.words.len() {
            let start = self.word;
            let first = self.read()?;
            let word_count = first >> WORD_COUNT_SHIFT;
            let opcode = first & OPCODE_MASK;
            let next = start + word_count as usize;
            if next > self.words.len() {
                return Err(Killed("stream instruction terminated too early"));
            }
            if word_count == 0 {
                return Err(Killed("instruction with a word count of 0"));
            }
            let mut operands = i64::from(word_count) - 1;
            let instruction = tables::instruction(opcode);
            let mut type_id = 0;
            if instruction.ty {
                type_id = self.read()?;
                operands -= 1;
            }
            let mut result_id = 0;
            if instruction.result {
                result_id = self.read()?;
                operands -= 1;
                if result_id >= self.bound {
                    return Err(Killed(BAD_ID));
                }
            }
            self.output_result_id(result_id)?;
            self.output_type_id(type_id)?;
            self.output_indent();
            self.disassemble_instruction(result_id, opcode, operands)?;
            if self.word != next {
                let word = self.word;
                self.text(&format!(
                    " ERROR, incorrect number of operands consumed.  At {word} instead of {next} instruction start was {start}"
                ));
                self.word = next;
            }
            self.text("\n");
        }
        Ok(())
    }

    fn output_indent(&mut self) {
        for _ in 0..self.nested.len() {
            self.text("  ");
        }
    }

    fn format_id(&self, id: u32) -> Step<Vec<u8>> {
        let mut text = Vec::new();
        if id != 0 {
            if id >= self.bound {
                return Err(Killed(BAD_ID));
            }
            text.extend_from_slice(id.to_string().as_bytes());
            let descriptor = self.descriptor(id);
            if !descriptor.is_empty() {
                text.push(b'(');
                text.extend_from_slice(descriptor);
                text.push(b')');
            }
        }
        Ok(text)
    }

    fn padded(&mut self, text: &[u8], width: usize) {
        for _ in text.len()..width {
            self.out.push(b' ');
        }
        self.out.extend_from_slice(text);
    }

    fn output_result_id(&mut self, id: u32) -> Step {
        let text = self.format_id(id)?;
        self.padded(&text, 16);
        self.text(if id != 0 { ":" } else { " " });
        if !self.nested.is_empty() && self.nested.last() == Some(&id) {
            self.nested.pop();
        }
        Ok(())
    }

    fn output_type_id(&mut self, id: u32) -> Step {
        let text = self.format_id(id)?;
        self.padded(&text, 12);
        self.text(" ");
        Ok(())
    }

    fn output_id(&mut self, id: u32) -> Step {
        if id >= self.bound {
            return Err(Killed(BAD_ID));
        }
        self.number(id);
        let descriptor = self.descriptor(id).to_vec();
        if !descriptor.is_empty() {
            self.out.push(b'(');
            self.out.extend_from_slice(&descriptor);
            self.out.push(b')');
        }
        Ok(())
    }

    fn output_mask(&mut self, kind: Kind, mask: u32) {
        if mask == 0 {
            self.text("None");
            return;
        }
        let class = tables::enum_class(kind);
        for bit in 0..class.ceiling.min(32) {
            if mask & (1 << bit) != 0 {
                self.text((class.name)(bit));
                self.text(" ");
            }
        }
    }

    fn disassemble_immediates(&mut self, count: i64) -> Step {
        for index in 0..count {
            let value = self.read()?;
            self.number(value);
            if index < count - 1 {
                self.text(" ");
            }
        }
        Ok(())
    }

    fn disassemble_ids(&mut self, count: i64) -> Step {
        for index in 0..count {
            let id = self.read()?;
            self.output_id(id)?;
            if index < count - 1 {
                self.text(" ");
            }
        }
        Ok(())
    }

    fn decode_string(&self) -> Step<(usize, Vec<u8>)> {
        let mut text = Vec::new();
        let mut position = self.word;
        loop {
            let Some(&content) = self.words.get(position) else {
                return Err(Killed("string operand runs off the end of the stream"));
            };
            position += 1;
            for byte in content.to_le_bytes() {
                if byte == 0 {
                    return Ok((position - self.word, text));
                }
                text.push(byte);
            }
        }
    }

    fn disassemble_string(&mut self) -> Step<i64> {
        self.text(" \"");
        let (count, text) = self.decode_string()?;
        self.out.extend_from_slice(&text);
        self.text("\"");
        self.word += count;
        Ok(i64::try_from(count).unwrap_or(i64::MAX))
    }

    fn describe_type(&mut self, result_id: u32, opcode: u32, operands: i64) -> Step {
        let descriptor: Vec<u8> = match opcode {
            OP_TYPE_INT => match self.peek(0)? {
                8 => b"int8_t".to_vec(),
                16 => b"int16_t".to_vec(),
                64 => b"int64_t".to_vec(),
                _ => b"int".to_vec(),
            },
            OP_TYPE_FLOAT => match self.peek(0)? {
                4 | 6 | 8 | 16 if operands > 1 => match self.peek(1)? {
                    4214 => b"floate4m3_t".to_vec(),
                    4215 => b"floate5m2_t".to_vec(),
                    4225 => b"floate2m1_t".to_vec(),
                    4224 => b"floate3m2_t".to_vec(),
                    4223 => b"floate2m3_t".to_vec(),
                    4226 => b"floatue8m0_t".to_vec(),
                    4227 => b"floatmxint8_t".to_vec(),
                    _ => b"bfloat16_t".to_vec(),
                },
                4 | 6 | 8 | 16 => b"float16_t".to_vec(),
                64 => b"float64_t".to_vec(),
                _ => b"float".to_vec(),
            },
            OP_TYPE_BOOL => b"bool".to_vec(),
            OP_TYPE_STRUCT => b"struct".to_vec(),
            OP_TYPE_POINTER | OP_TYPE_UNTYPED_POINTER_KHR => b"ptr".to_vec(),
            OP_TYPE_VECTOR => {
                let component = self.peek(0)?;
                if component >= self.bound {
                    return Err(Killed(BAD_ID));
                }
                let mut text = Vec::new();
                let inner = self.descriptor(component);
                if !inner.is_empty() {
                    let prefix = if inner.starts_with(b"bf") { 2 } else { 1 };
                    text.extend_from_slice(inner.get(..prefix).unwrap_or(inner));
                    for size in [&b"8"[..], b"16", b"64"] {
                        if inner.windows(size.len()).any(|window| window == size) {
                            text.extend_from_slice(size);
                        }
                    }
                }
                text.extend_from_slice(b"vec");
                let count = self.peek(1)?;
                if matches!(count, 2 | 3 | 4 | 8 | 16 | 32) {
                    text.extend_from_slice(count.to_string().as_bytes());
                }
                text
            }
            _ => return Ok(()),
        };
        self.descriptors.insert(result_id, descriptor);
        Ok(())
    }

    fn disassemble_instruction(&mut self, result_id: u32, opcode: u32, mut operands: i64) -> Step {
        let name = tables::opcode(opcode);
        self.text(name.get(2..).unwrap_or(""));

        match opcode {
            OP_LOOP_MERGE | OP_SELECTION_MERGE => self.next_nested = self.peek(0)?,
            OP_BRANCH_CONDITIONAL | OP_SWITCH => {
                if self.next_nested != 0 {
                    self.nested.push(self.next_nested);
                    self.next_nested = 0;
                }
            }
            OP_EXT_INST_IMPORT => {
                let (_, text) = self.decode_string()?;
                self.descriptors.insert(result_id, text);
            }
            _ => {
                if result_id != 0 && self.descriptor(result_id).is_empty() {
                    self.describe_type(result_id, opcode, operands)?;
                }
            }
        }

        if opcode == OP_TYPE_IMAGE {
            return self.disassemble_image(operands);
        }

        let classes = tables::instruction(opcode).operands;
        for &class in classes {
            if operands <= 0 {
                break;
            }
            self.text(" ");
            match class {
                Class::Id | Class::Enum(Kind::Scope) | Class::Enum(Kind::MemorySemantics) => {
                    self.disassemble_ids(1)?;
                    operands -= 1;
                    if opcode == OP_NAME {
                        let target = self.previous(1);
                        let (_, text) = self.decode_string()?;
                        self.descriptors.insert(target, text);
                    }
                }
                Class::VariableIds => return self.disassemble_ids(operands),
                Class::Enum(Kind::ImageOperands) => {
                    let mask = self.read()?;
                    self.output_mask(Kind::ImageOperands, mask);
                    operands -= 1;
                    return self.disassemble_ids(operands);
                }
                Class::OptionalLiteral | Class::VariableLiterals => {
                    if (opcode == OP_DECORATE || opcode == OP_MEMBER_DECORATE)
                        && self.previous(1) == DECORATION_BUILT_IN
                    {
                        let value = self.read()?;
                        self.text(tables::built_in(value));
                        operands -= 1;
                    }
                    return self.disassemble_immediates(operands);
                }
                Class::VariableIdLiteral => {
                    while operands > 0 {
                        self.continuation_line()?;
                        self.text("     Type ");
                        self.disassemble_ids(1)?;
                        self.text(", member ");
                        self.disassemble_immediates(1)?;
                        operands -= 2;
                    }
                    return Ok(());
                }
                Class::VariableLiteralId => {
                    while operands > 0 {
                        self.continuation_line()?;
                        self.text("     case ");
                        self.disassemble_immediates(1)?;
                        self.text(": ");
                        self.disassemble_ids(1)?;
                        operands -= 2;
                    }
                    return Ok(());
                }
                Class::LiteralNumber => {
                    self.disassemble_immediates(1)?;
                    operands -= 1;
                    if opcode == OP_EXT_INST {
                        self.ext_inst_name();
                    }
                }
                Class::LiteralString => operands -= self.disassemble_string()?,
                Class::VariableLiteralStrings => {
                    while operands > 0 {
                        operands -= self.disassemble_string()?;
                    }
                    return Ok(());
                }
                Class::Enum(Kind::MemoryAccess) => {
                    let mask = self.read()?;
                    self.output_mask(Kind::MemoryAccess, mask);
                    operands -= 1;
                    if operands != 0 && mask == 0 {
                        self.text(" ");
                    }
                    if mask & MEMORY_ACCESS_ALIGNED != 0 {
                        self.disassemble_immediates(1)?;
                        operands -= 1;
                        if operands != 0 {
                            self.text(" ");
                        }
                    }
                    let count = i64::from((mask & MEMORY_ACCESS_POINTER_IDS).count_ones());
                    self.disassemble_ids(count)?;
                    operands -= count;
                }
                Class::Enum(Kind::TensorAddressingOperands) => {
                    let mask = self.read()?;
                    self.output_mask(Kind::TensorAddressingOperands, mask);
                    operands -= 1;
                    if operands != 0 && mask == 0 {
                        self.text(" ");
                    }
                    let count = i64::from(mask.count_ones());
                    self.disassemble_ids(count)?;
                    operands -= count;
                }
                Class::Enum(kind) => {
                    let class = tables::enum_class(kind);
                    let value = self.read()?;
                    if class.bitmask {
                        self.output_mask(kind, value);
                    } else {
                        self.text((class.name)(value));
                    }
                    operands -= 1;
                }
            }
        }
        Ok(())
    }

    fn continuation_line(&mut self) -> Step {
        self.text("\n");
        self.output_result_id(0)?;
        self.output_type_id(0)?;
        self.output_indent();
        Ok(())
    }

    fn disassemble_image(&mut self, operands: i64) -> Step {
        self.text(" ");
        self.disassemble_ids(1)?;
        self.text(" ");
        let dimension = self.read()?;
        self.text(tables::dimension(dimension));
        if self.read()? != 0 {
            self.text(" depth");
        }
        if self.read()? != 0 {
            self.text(" array");
        }
        if self.read()? != 0 {
            self.text(" multi-sampled");
        }
        match self.read()? {
            0 => self.text(" runtime"),
            1 => self.text(" sampled"),
            2 => self.text(" nonsampled"),
            _ => {}
        }
        self.text(" format:");
        let format = self.read()?;
        self.text(tables::image_format(format));
        if operands == 8 {
            self.text(" ");
            let qualifier = self.read()?;
            self.text(tables::access_qualifier(qualifier));
        }
        Ok(())
    }

    fn ext_inst_set(name: &[u8]) -> ExtSet {
        match name {
            b"OpenCL.std" | b"OpenCL.DebugInfo.100" => ExtSet::OpenCl,
            b"NonSemantic.DebugPrintf" => ExtSet::DebugPrintf,
            b"NonSemantic.DebugBreak" => ExtSet::DebugBreak,
            _ if name.starts_with(b"NonSemantic.Shader.DebugInfo.") => ExtSet::ShaderDebugInfo,
            _ if ext::AMD_SETS.contains(&name) => ExtSet::Amd,
            _ if ext::NV_SETS.contains(&name) => ExtSet::Nv,
            _ => ExtSet::Glsl450,
        }
    }

    fn ext_inst_name(&mut self) {
        let set = self.previous(2);
        let entry = self.previous(1);
        let name = self.descriptor(set).to_vec();
        let text = match Self::ext_inst_set(&name) {
            ExtSet::Glsl450 if entry < ext::GLSL_STD_450_COUNT => ext::glsl_std_450(entry),
            ExtSet::Glsl450 | ExtSet::OpenCl => return,
            ExtSet::Amd => ext::amd(&name, entry),
            ExtSet::Nv => ext::nv(&name, entry),
            ExtSet::DebugPrintf => "DebugPrintf",
            ExtSet::DebugBreak => "DebugBreak",
            ExtSet::ShaderDebugInfo => ext::shader_debug_info(entry),
        };
        self.text("(");
        self.text(text);
        self.text(")");
    }
}
